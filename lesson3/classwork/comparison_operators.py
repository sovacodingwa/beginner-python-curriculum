print(5 > 3) # Greater than
print(3 < 5) # Less than
print(5 >= 5) # Greater than or equal to
print(4 <= 4) # Less than or equal to
print(5 == 5) # Equal to operator
print(5 != 3) # Not equal to operator

# You can compare variables too
a = 10
b = 7
print(a > b)
print(a == b)

x = int(input("Enter a number: "))
y = int(input("Enter another number: "))
print(x > y)

print("apple" == "apple") # Equal to
print("apple" == "Apple") # Case sensitive
print("apple" != "banana") # Not equal to
print("cat" > "bat") # Compare alphabetically
print("dog" < "zebra")